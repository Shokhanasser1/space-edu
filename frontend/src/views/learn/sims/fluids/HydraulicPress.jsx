/** Russian noun after a number: 1 качок, 2 качка, 5 качков (decimals take the "few" form). */
function ru(n, one, few, many) {
  const str = String(n);
  if (/[.,]/.test(str)) return few;
  const v = Math.abs(parseInt(str.replace(/\D/g, ''), 10)) % 100;
  if (v % 10 === 1 && v !== 11) return one;
  if (v % 10 >= 2 && v % 10 <= 4 && (v < 12 || v > 14)) return few;
  return many;
}
