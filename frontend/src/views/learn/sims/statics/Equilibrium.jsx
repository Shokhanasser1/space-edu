/**
 * Lesson "Muvozanat shartlari" (Statics, lesson index 1): the two conditions
 * of equilibrium of a rigid body —
 *   ΣF = 0 (the resultant is zero: no translation) and
 *   ΣM = 0 (the moments about any axis add up to zero: no rotation),
 * with the moment of a force M = F·d (d — the lever arm), the lever rule
 * F₁d₁ = F₂d₂ and its golden rule, and the three kinds of equilibrium.
 * Four labs: a lever on a stand, the moment on a door, a sign on two ropes
 * (ΣF = 0 by vectors), and balls in a bowl / on a hump / on a table.
 * Subscripts in the strings are written as `F_{1}` (see `Sym`).
 */

/** "раз" / "раза" after a number in Russian. */
function raz(k) {
  const n = Number(String(k).replace(',', '.'));
  if (!Number.isInteger(n)) return 'раза';
  const d = n % 10;
  const dd = n % 100;
  return d >= 2 && d <= 4 && (dd < 12 || dd > 14) ? 'раза' : 'раз';
}

